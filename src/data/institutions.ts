  // ⚠️ לא ממציאים מספרים. שדה ריק = "אין לנו, הרכזת תשיג".
  // הכלל: להפנות ליחידת התמיכה / הרכז הייעודי — לא למדור הרישום הכללי,
  // שם עונים "אינך עומד בתנאים" ולא מכירים את מסלולי הקבלה החלופיים.
