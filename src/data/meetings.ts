export const PROGRAM_START = "2026-09-01";

/** פגישה שקדמה לתוכנית — נשמרת, מוצגת בנפרד, ואינה נספרת כממתינה לסימון */
export function isPreProgram(startTime: string | Date): boolean {
  const t = typeof startTime === "string" ? startTime : startTime.toISOString();
  return t < PROGRAM_START;
}
