-- טלפון מאומת מול טלפון שהוקלד (נתי, 8.10).
--
-- היו משתתפים שלא הסתדרו עם אימות ה-SMS ונכנסו בלי טלפון. בלעדיו הם
-- **בלתי נראים לכל החיבורים**: הזמנת Cal לא מותאמת, השורה בלוח לא
-- מתחברת, והרכזת לא רואה שהם בכלל נכנסו.
--
-- ⚠️ ולכן מותר לרכז/ת להקליד טלפון — **אבל חייבים לדעת שהוא הוקלד.**
-- טלפון מ-OTP הוא הוכחה שהמכשיר ביד שלו; טלפון שהוקלד הוא טענה. השימוש
-- היחיד שדורש הוכחה הוא **שיוך לקוהורט** (alumni_roster) — שם קישור
-- שדולף ומספר שמישהו ניחש היו מכניסים אדם למסע הלא נכון.
-- לכל השאר (התאמת פגישות, חיבור ללוח, תצוגה) טענה מספיקה.
alter table candidates add column if not exists phone_verified boolean not null default false;

-- כל מי שיש לו טלפון היום הגיע מ-OTP — לא הייתה דרך אחרת להזין אותו.
update candidates set phone_verified = true where coalesce(phone, '') <> '';
